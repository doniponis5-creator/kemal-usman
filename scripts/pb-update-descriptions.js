/**
 * pb-update-descriptions.js — updates product descriptions in PocketBase
 * with professional perfume note pyramids and descriptions in Russian.
 *
 *   Run from repo root:  node scripts/pb-update-descriptions.js
 *   Requires .env with PB_ADMIN_EMAIL + PB_ADMIN_PASSWORD.
 *
 *   Only updates products whose current description is missing or short (<100 chars).
 *   Matching is case-insensitive partial match on product name.
 */

try { await import('dotenv/config'); } catch {
  console.error('Missing dependency `dotenv`. Run: npm install dotenv');
  process.exit(1);
}

const PB_URL = (process.env.PB_URL || process.env.VITE_PB_URL || 'http://145.223.100.16:8090').replace(/\/$/, '');
const EMAIL = process.env.PB_ADMIN_EMAIL;
const PASSWORD = process.env.PB_ADMIN_PASSWORD;

if (!EMAIL || !PASSWORD) {
  console.error('PB_ADMIN_EMAIL and PB_ADMIN_PASSWORD must be set in .env');
  process.exit(1);
}

const log = (...a) => console.log('[pb-update-descriptions]', ...a);

// ──────────────────────────────────────────────────
// HTTP + Auth helpers (same pattern as other scripts)
// ──────────────────────────────────────────────────

async function http(path, init = {}) {
  const res = await fetch(`${PB_URL}${path}`, {
    ...init,
    headers: { 'Content-Type': 'application/json', ...(init.headers || {}) },
  });
  const text = await res.text();
  let body;
  try { body = text ? JSON.parse(text) : null; } catch { body = text; }
  if (!res.ok) {
    const msg = body?.message || res.statusText;
    throw new Error(`${res.status} ${msg} — ${JSON.stringify(body)}`);
  }
  return body;
}

async function authAdmin() {
  const payload = JSON.stringify({ identity: EMAIL, password: PASSWORD });
  for (const path of [
    '/api/collections/_superusers/auth-with-password',
    '/api/admins/auth-with-password',
  ]) {
    try {
      const r = await http(path, { method: 'POST', body: payload });
      return r.token;
    } catch (e) {
      if (!String(e.message).startsWith('404')) throw e;
    }
  }
  throw new Error('No admin auth endpoint responded — check PB version / URL.');
}

