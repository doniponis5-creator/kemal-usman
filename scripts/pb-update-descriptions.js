async function main() {
  log('PB_URL =', PB_URL);
  const token = await authAdmin();
  log('admin authenticated');

  const auth = { Authorization: token };

  // Fetch ALL products (paginate)
  let page = 1;
  let allProducts = [];
  while (true) {
    const res = await http(`/api/collections/products/records?page=${page}&perPage=200`, { headers: auth });
    allProducts = allProducts.concat(res.items || []);
    if (page >= res.totalPages) break;
    page++;
  }
  log(`fetched ${allProducts.length} products`);

  let updated = 0;
  let skipped = 0;
  let noMatch = 0;

  for (const product of allProducts) {
    const name = product.name || '';
    const brand = product.brand || '';

    // Skip if already has a long description
    if (product.description && product.description.length > 100) {
      skipped++;
      continue;
    }

    const matchKey = findDescription(name, brand);
    if (!matchKey) {
      log(`  NO MATCH: "${brand} ${name}"`);
      noMatch++;
      continue;
    }

    const description = DESCRIPTIONS[matchKey];

    try {
      await http(`/api/collections/products/records/${product.id}`, {
        method: 'PATCH',
        headers: auth,
        body: JSON.stringify({ description }),
      });
      log(`  UPDATED: "${brand} ${name}" -> matched "${matchKey}"`);
      updated++;
    } catch (e) {
      log(`  ERROR updating "${brand} ${name}": ${e.message}`);
    }
  }

  log('');
  log('=== SUMMARY ===');
  log(`Total products: ${allProducts.length}`);
  log(`Updated:        ${updated}`);
  log(`Skipped (existing description): ${skipped}`);
  log(`No match found: ${noMatch}`);
}

main().catch((e) => {
  console.error('ERROR:', e.message || e);
  process.exit(1);
});
