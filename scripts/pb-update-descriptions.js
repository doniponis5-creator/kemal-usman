/** Normalize a string for fuzzy matching */
function norm(s) {
  return s
    .toLowerCase()
    .replace(/[''’`]/g, "'")
    .replace(/[^a-z0-9а-яёéèê' ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Try to find a matching description key for a product.
 * Tries exact-ish match first, then partial.
 */
function findDescription(productName, productBrand) {
  const pName = norm(productName || '');
  const pBrand = norm(productBrand || '');
  const combined = `${pBrand} ${pName}`;

  // 1. Try exact key match
  for (const key of Object.keys(DESCRIPTIONS)) {
    const nKey = norm(key);
    if (nKey === combined || nKey === pName) return key;
  }

  // 2. Try if product name contains the key or vice versa
  for (const key of Object.keys(DESCRIPTIONS)) {
    const nKey = norm(key);
    if (combined.includes(nKey) || nKey.includes(combined)) return key;
  }

  // 3. Try partial — key words present in product name
  for (const key of Object.keys(DESCRIPTIONS)) {
    const parts = norm(key).split(' ').filter(p => p.length > 2);
    // If at least 60% of key words appear in the product name+brand
    const hits = parts.filter(p => combined.includes(p));
    if (parts.length > 0 && hits.length / parts.length >= 0.6) return key;
  }

  return null;
}

